#include "CodeWriter.h"

#include <functional>
#include <sstream>

namespace Reflect {

    namespace {
        // A property's type as the engine's PropertyType names it, and what it refers to.
        struct ResolvedType {
            const char* Kind = nullptr;
            const EnumDef* Enum = nullptr;
            const StructDef* Struct = nullptr;
        };

        std::string ReplaceAll(std::string text, const std::string& from, const std::string& to) {
            for (size_t at = text.find(from); at != std::string::npos; at = text.find(from, at + to.size())) {
                text.replace(at, from.size(), to);
            }
            return text;
        }

        bool EndsWith(const std::string& text, const std::string& suffix) {
            return text.size() >= suffix.size() && text.compare(text.size() - suffix.size(), suffix.size(), suffix) == 0;
        }

        class Writer {
        public:
            Writer(const ReflectionModel& model, std::string registerFunction, bool forGame)
                : m_Model(model), m_RegisterFunction(std::move(registerFunction)), m_ForGame(forGame) {}

            std::string Run() {
                Prepare();
                return m_ForGame ? WriteGame() : WriteEngine();
            }

        private:
            void Prepare() {
                IndexNames();
                for (const StructDef& definition : m_Model.Structs) {
                    for (const PropertyDef& property : definition.Properties) {
                        Resolve(property);
                    }
                }
                OrderStructs();
            }

            std::string WriteEngine() {
                m_Out << "// Generated by VKE_Reflect from the marks in the headers below. Don't edit it: change the\n"
                         "// marks and rebuild.\n";
                for (const std::string& include : m_Model.Includes) {
                    m_Out << "//   " << include << "\n";
                }
                m_Out << "\n#include <scene/ComponentRegistry.h>\n#include <scene/Properties.h>\n\n";
                for (const std::string& include : m_Model.Includes) {
                    m_Out << "#include <" << include << ">\n";
                }
                m_Out << "\nnamespace VKE::Scene {\n\n";
                m_Out << "    // A member of the registry, which every component befriends, so the tables can reach\n"
                         "    // private members.\n";
                m_Out << "    void ComponentRegistry::" << m_RegisterFunction << "() {\n";

                for (const EnumDef& definition : m_Model.Enums) {
                    WriteEnum(definition);
                }
                for (const StructDef* definition : m_StructOrder) {
                    WriteStruct(*definition);
                }
                for (const StructDef& definition : m_Model.Structs) {
                    if (!definition.IsComponent) continue;
                    m_Out << "        Register<::" << definition.QualifiedName << ">(k" << definition.Name
                          << (definition.Addable ? "" : ", false") << ");\n";
                }

                m_Out << "    }\n\n";
                m_Out << "} // namespace VKE::Scene\n";
                return m_Out.str();
            }

            std::string WriteGame() {
                m_Out << "// Generated by VKE_Reflect from the marks in the game's headers. Don't edit it.\n\n";
                m_Out << "#include <vke/detail/ApiTable.h>\n#include <vke/detail/GameInfo.h>\n\n";
                for (const std::string& include : m_Model.Includes) {
                    m_Out << "#include <" << include << ">\n";
                }
                m_Out << "\nnamespace vke::detail {\n\n";
                m_Out << "    // Every script befriends this, so the tables can reach private members.\n";
                m_Out << "    const GameInfo& ScriptTables::GetGame() {\n";

                for (const EnumDef& definition : m_Model.Enums) {
                    WriteEnum(definition);
                }
                for (const StructDef* definition : m_StructOrder) {
                    WriteStruct(*definition);
                }

                size_t scripts = 0;
                std::ostringstream entries;
                for (const StructDef& definition : m_Model.Structs) {
                    if (!definition.IsComponent) continue;
                    ++scripts;
                    entries << "            {\"" << definition.Name << "\", &k" << definition.Name
                            << ",\n             []() -> void* { return new ::" << definition.QualifiedName
                            << "(); },\n             [](void* script) { delete static_cast<::"
                            << definition.QualifiedName << "*>(script); },\n             [](void* script) -> Script* { "
                            << "return static_cast<::" << definition.QualifiedName << "*>(script); },\n             "
                            << "UsesUpdate<::" << definition.QualifiedName << ">(), UsesLateUpdate<::"
                            << definition.QualifiedName << ">()},\n";
                }
                if (scripts > 0) {
                    m_Out << "        static const ScriptTypeInfo kScripts[] = {\n" << entries.str() << "        };\n";
                }
                m_Out << "        static const GameInfo kGame = {kApiVersion, "
                      << (scripts > 0 ? "kScripts" : "nullptr") << ", " << scripts << ", &GetCalls()};\n";
                m_Out << "        return kGame;\n    }\n\n} // namespace vke::detail\n\n";
                m_Out << "#include <vke/detail/ApiCalls.inl>\n\n";
                m_Out << "extern \"C\" __declspec(dllexport) const vke::detail::GameInfo* VkeLoadGame(\n"
                         "    const vke::detail::ApiTable* api) {\n"
                         "    vke::detail::g_Api = api;\n"
                         "    return &vke::detail::ScriptTables::GetGame();\n}\n";
                return m_Out.str();
            }

            [[noreturn]] void Fail(const SourceLocation& location, const std::string& message) const {
                throw ReflectError{location, message};
            }

            // Enums and structs are looked up by their own name, so it must be unique.
            void IndexNames() {
                std::map<std::string, SourceLocation> seen;
                auto add = [&](const std::string& name, const SourceLocation& location) {
                    auto [it, added] = seen.emplace(name, location);
                    if (!added) {
                        Fail(location, "'" + name + "' is already the name of a marked type, at " + it->second.File +
                                           "(" + std::to_string(it->second.Line) + ")");
                    }
                };
                for (const EnumDef& definition : m_Model.Enums) {
                    add(definition.Name, definition.Location);
                    m_Enums[definition.Name] = &definition;
                }
                for (const StructDef& definition : m_Model.Structs) {
                    add(definition.Name, definition.Location);
                    if (!definition.IsComponent) m_Structs[definition.Name] = &definition;
                }
            }

            ResolvedType Resolve(const PropertyDef& property) {
                auto cached = m_Resolved.find(&property);
                if (cached != m_Resolved.end()) return cached->second;

                // The engine's own namespace, or the SDK's in a game, is optional in type names.
                std::string type = ReplaceAll(property.TypeText, m_ForGame ? "vke::" : "VKE::", "");
                if (type.rfind("::", 0) == 0) type.erase(0, 2);

                ResolvedType resolved;
                if (type == "bool") {
                    resolved.Kind = "Bool";
                } else if (type == "f32" || type == "float") {
                    resolved.Kind = "F32";
                } else if (type == "Vec3" || (!m_ForGame && type == "glm::vec3")) {
                    resolved.Kind = "Vec3";
                } else if (type == "Quat" || (!m_ForGame && type == "glm::quat")) {
                    resolved.Kind = "Quat";
                } else if (m_ForGame && type == "int") {
                    resolved.Kind = "I32";
                } else if (m_ForGame && (type == "ObjectRef" || type.rfind("ScriptRef<", 0) == 0)) {
                    resolved.Kind = "Object";
                } else if (m_ForGame && type == "PrefabRef") {
                    resolved.Kind = "Prefab";
                } else if (m_ForGame && type == "MeshRef") {
                    resolved.Kind = "MeshAsset";
                } else if (m_ForGame && type == "MaterialRef") {
                    resolved.Kind = "MaterialAsset";
                } else if (m_ForGame && type == "SceneRef") {
                    resolved.Kind = "SceneAsset";
                } else if (!m_ForGame && type == "Handle<Assets::MeshData>") {
                    resolved.Kind = "Mesh";
                } else if (!m_ForGame && type == "std::vector<Handle<Assets::MaterialData>>") {
                    resolved.Kind = "Materials";
                } else if (type.find('<') == std::string::npos) {
                    std::string name = type.substr(type.rfind("::") == std::string::npos ? 0 : type.rfind("::") + 2);
                    if (auto it = m_Enums.find(name); it != m_Enums.end() && EndsWith(it->second->QualifiedName, type)) {
                        resolved.Kind = "Enum";
                        resolved.Enum = it->second;
                    } else if (auto it = m_Structs.find(name);
                               it != m_Structs.end() && EndsWith(it->second->QualifiedName, type)) {
                        resolved.Kind = "Struct";
                        resolved.Struct = it->second;
                    }
                }

                if (!resolved.Kind) {
                    Fail(property.Location, "'" + property.TypeText + "' isn't a type properties can have; mark it with "
                                            "VKE_ENUM or VKE_STRUCT, or see reflection/Marks.h");
                }
                if ((!property.Min.empty() || !property.Max.empty()) && std::string(resolved.Kind) != "F32") {
                    Fail(property.Location, "Min and Max only apply to f32 properties");
                }
                if (property.Display == "Color" && std::string(resolved.Kind) != "Vec3") {
                    Fail(property.Location, "Display = Color only applies to Vec3 properties");
                }
                if (property.Display == "Angle" && std::string(resolved.Kind) != "F32") {
                    Fail(property.Location, "Display = Angle only applies to f32 properties");
                }
                m_Resolved[&property] = resolved;
                return resolved;
            }

            // Structs before the structs and components that contain them.
            void OrderStructs() {
                std::map<const StructDef*, int> state;
                std::function<void(const StructDef&)> visit = [&](const StructDef& definition) {
                    int& mark = state[&definition];
                    if (mark == 2) return;
                    if (mark == 1) Fail(definition.Location, "'" + definition.Name + "' contains itself");
                    mark = 1;
                    for (const PropertyDef& property : definition.Properties) {
                        if (const StructDef* inner = Resolve(property).Struct) visit(*inner);
                    }
                    mark = 2;
                    m_StructOrder.push_back(&definition);
                };
                for (const StructDef& definition : m_Model.Structs) {
                    visit(definition);
                }
            }

            void WriteEnum(const EnumDef& definition) {
                m_Out << "        static const EnumValue k" << definition.Name << "Values[] = {\n";
                for (const auto& [name, value] : definition.Values) {
                    m_Out << "            {\"" << name << "\", " << value << "u},\n";
                }
                m_Out << "        };\n";
                m_Out << "        static const EnumInfo k" << definition.Name << " = {\"" << definition.Name << "\", k"
                      << definition.Name << "Values, " << definition.Values.size() << ", sizeof(::"
                      << definition.QualifiedName << ")};\n\n";
            }

            void WriteStruct(const StructDef& definition) {
                const std::string& name = definition.Name;
                if (!definition.Properties.empty()) {
                    m_Out << "        static const PropertyInfo k" << name << "Properties[] = {\n";
                    for (const PropertyDef& property : definition.Properties) {
                        ResolvedType type = Resolve(property);
                        m_Out << "            {\"" << property.SavedName << "\", PropertyType::" << type.Kind
                              << ",\n             [](void* object) -> void* { return &static_cast<::"
                              << definition.QualifiedName << "*>(object)->" << property.Member << "; },\n             "
                              << (type.Enum ? "&k" + type.Enum->Name : "nullptr") << ", "
                              << (type.Struct ? "&k" + type.Struct->Name : "nullptr") << ", "
                              << (property.Min.empty() ? "kNoMinimum" : "static_cast<float>(" + property.Min + ")")
                              << ", "
                              << (property.Max.empty() ? "kNoMaximum" : "static_cast<float>(" + property.Max + ")")
                              << ", PropertyDisplay::" << (property.Display.empty() ? "Default" : property.Display)
                              << "},\n";
                    }
                    m_Out << "        };\n";
                }
                m_Out << "        static const StructInfo k" << name << " = {\"" << name << "\", "
                      << (definition.Properties.empty() ? "nullptr" : "k" + name + "Properties") << ", "
                      << definition.Properties.size() << "};\n\n";
            }

            const ReflectionModel& m_Model;
            std::string m_RegisterFunction;
            bool m_ForGame;
            std::ostringstream m_Out;
            std::map<std::string, const EnumDef*> m_Enums;
            std::map<std::string, const StructDef*> m_Structs;
            std::map<const PropertyDef*, ResolvedType> m_Resolved;
            std::vector<const StructDef*> m_StructOrder;
        };

        // "Log_Info" for vke::Log::Info and "Object_IsValid" for vke::Object::IsValid: the
        // function's name in the engine's table.
        std::string GetEntryName(const ApiFunctionDef& function) {
            std::string path = function.Namespace == "vke" ? "" : function.Namespace.substr(5) + "::";
            if (!function.Class.empty()) path += function.Class + "::";
            return ReplaceAll(path, "::", "_") + function.Name;
        }

        bool TakesObject(const ApiFunctionDef& function) {
            return !function.Class.empty() && !function.IsStatic;
        }

        std::string GetParameters(const ApiFunctionDef& function, bool withObject) {
            std::string text = withObject && TakesObject(function) ? function.Class + " self" : "";
            for (const ParameterDef& parameter : function.Parameters) {
                text += (text.empty() ? "" : ", ") + parameter.Type + " " + parameter.Name;
            }
            return text;
        }

        std::string GetArguments(const ApiFunctionDef& function) {
            std::string text = TakesObject(function) ? "*this" : "";
            for (const ParameterDef& parameter : function.Parameters) {
                text += (text.empty() ? "" : ", ") + parameter.Name;
            }
            return text;
        }

        std::string WriteApiTable(const ReflectionModel& model) {
            std::ostringstream out;
            out << "// Generated by VKE_Reflect from the SDK's headers. Don't edit it.\n#pragma once\n\n";
            for (const std::string& include : model.Includes) {
                out << "#include <" << include << ">\n";
            }
            out << "\nnamespace vke::detail {\n\n";
            out << "    // Changes with the SDK's headers. The engine refuses a game built with another version.\n";
            out << "    inline constexpr unsigned kApiVersion = " << model.TokenHash << "u;\n\n";
            out << "    // What the engine gives a game when it loads it.\n    struct ApiTable {\n";
            for (const ApiFunctionDef& function : model.Functions) {
                out << "        " << function.ReturnType << " (*" << GetEntryName(function) << ")("
                    << GetParameters(function, true) << ");\n";
            }
            out << "    };\n\n    extern const ApiTable* g_Api;\n\n} // namespace vke::detail\n";
            return out.str();
        }

        std::string WriteApiCalls(const ReflectionModel& model) {
            std::ostringstream out;
            out << "// Generated by VKE_Reflect from the SDK's headers. Don't edit it. Built into a game's DLL.\n\n";
            out << "const vke::detail::ApiTable* vke::detail::g_Api = nullptr;\n\n";
            for (const ApiFunctionDef& function : model.Functions) {
                out << "namespace " << function.Namespace << " {\n";
                std::string scope = function.Class.empty() ? "" : function.Class + "::";
                out << "    " << function.ReturnType << " " << scope << function.Name << "("
                    << GetParameters(function, false) << ")" << (function.IsConst ? " const" : "") << " {\n";
                out << "        " << (function.ReturnType == "void" ? "" : "return ") << "::vke::detail::g_Api->"
                    << GetEntryName(function) << "(" << GetArguments(function) << ");\n";
                out << "    }\n}\n\n";
            }
            return out.str();
        }

        std::string WriteApiBindings(const ReflectionModel& model) {
            std::ostringstream out;
            out << "// Generated by VKE_Reflect from the SDK's headers. Don't edit it.\n#pragma once\n\n";
            out << "#include <vke/detail/ApiTable.h>\n\n";
            out << "// What the engine writes by hand, in Engine/Scripting/private/api, one per function of the SDK.\n";
            out << "namespace vke::api {\n";
            for (const ApiFunctionDef& function : model.Functions) {
                out << "    " << function.ReturnType << " " << GetEntryName(function) << "("
                    << GetParameters(function, true) << ");\n";
            }
            out << "} // namespace vke::api\n\nnamespace vke::detail {\n\n";
            out << "    inline ApiTable MakeApiTable() {\n        ApiTable table{};\n";
            for (const ApiFunctionDef& function : model.Functions) {
                std::string name = GetEntryName(function);
                out << "        table." << name << " = &api::" << name << ";\n";
            }
            out << "        return table;\n    }\n\n} // namespace vke::detail\n";
            return out.str();
        }
    } // namespace

    std::string WriteCode(const ReflectionModel& model, const std::string& registerFunction) {
        Writer writer(model, registerFunction, false);
        return writer.Run();
    }

    std::string WriteGameCode(const ReflectionModel& model) {
        Writer writer(model, std::string(), true);
        return writer.Run();
    }

    std::map<std::string, std::string> WriteApiFiles(const ReflectionModel& model) {
        return {{"ApiTable.h", WriteApiTable(model)},
                {"ApiCalls.inl", WriteApiCalls(model)},
                {"ApiBindings.h", WriteApiBindings(model)}};
    }

} // namespace Reflect
